const GROUPS = ["sleep", "home", "purity", "mosque", "food", "travel", "nature", "hardship", "people", "quran", "sunnah", "ruqya"]

const seen = new Set()
const out = DUAS.map(([id, group, title, arabic, english, reference, count = 1, note = null]) => {
  if (seen.has(id)) throw new Error(`Duplicate dua id ${id}`)
  seen.add(id)
  if (!GROUPS.includes(group)) throw new Error(`Unknown group ${group} for ${id}`)
  if (!arabic || !english || !reference) throw new Error(`Incomplete dua ${id}`)
  return { id, group, title, count, note, arabic, english, reference }
})
writeFileSync(join(root, "data", "duas.json"), JSON.stringify(out, null, 1) + "\n")
console.log(`Wrote ${out.length} duas in ${GROUPS.length} groups`)
