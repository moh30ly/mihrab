//
// Run: node scripts/build-duas.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = process.cwd()

/** Words `from`..`to` (1-based, inclusive) of an ayah, from the Uthmani text. */
function ayahWords(surah, ayah, from = 1, to) {
  const { verses } = JSON.parse(readFileSync(join(root, "data", "quran", `${surah}.json`), "utf8"))
  const words = verses[ayah - 1][0].split(" ")
  return words.slice(from - 1, to ?? words.length).join(" ")
}

/** One or more ayah slices, joined, without a shadda on the first letter left by the word before it. */
function quran(...parts) {
  const text = parts.map((p) => ayahWords(...p)).join(" ۝ ")
  return `﴿${text.replace(/^(.)ّ/u, "$1")}﴾`
}

